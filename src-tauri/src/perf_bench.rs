/// Decode exactly like develop_internal's prelude.
fn decode_like_production(bytes: &[u8]) -> (RawImage, f32) {
    let source = RawSource::new_from_slice(bytes);
    let decoder = rawler::get_decoder(&source).expect("no decoder");
    let mut raw_image = decoder
        .raw_image(&source, &RawDecodeParams::default(), false)
        .expect("raw_image failed");
    let white = raw_image.whitelevel.0.first().cloned().unwrap_or(u16::MAX as u32) as f32;
    let black = raw_image.blacklevel.levels.first().map(|r| r.as_f32()).unwrap_or(0.0);
    let rescale_factor = (u32::MAX as f32 - black) / (white - black).max(1.0);
    for level in raw_image.whitelevel.0.iter_mut() {
        *level = u32::MAX;
    }
    raw_image.wb_coeffs =
        crate::multi_exposure::neutralize_wb_if_multiexposure(raw_image.wb_coeffs, bytes);
    (raw_image, rescale_factor)
}

fn production_developer(fast: bool) -> RawDevelop {
    let mut d = RawDevelop::default();
    if fast {
        d.demosaic_algorithm = DemosaicAlgorithm::Speed;
    }
    d.steps.retain(|&s| s != ProcessingStep::SRgb);
    d
}

#[inline]
fn bench_srgb_to_linear(value: f32) -> f32 {
    if value <= 0.04045 {
        value / 12.92
    } else {
        ((value + 0.055) / 1.055).powf(3.0)
    }
}

/// Verbatim copy of develop_internal's ThreeColor post-develop loop (raw_processing.rs),
/// including the runtime `is_linear_format && apply_ungamma` branch (false for Bayer ARW,
/// passed through black_box so it stays a runtime check exactly as in production).
fn post_rescale_highlight(inter: &mut Intermediate, rescale_factor: f32, hc: f32, fast: bool) {
    let is_linear_format = std::hint::black_box(false);
    let apply_ungamma = std::hint::black_box(false);
    let safe_highlight_compression = hc.max(1.01);
    let clamp_limit = if fast { 1.0 } else { safe_highlight_compression };
    if let Intermediate::ThreeColor(pixels) = inter {
        pixels.data.iter_mut().for_each(|p| {
            let mut r = (p[0] * rescale_factor).max(0.0);
            let mut g = (p[1] * rescale_factor).max(0.0);
            let mut b = (p[2] * rescale_factor).max(0.0);
            if is_linear_format && apply_ungamma {
                r = bench_srgb_to_linear(r.clamp(0.0, 1.0));
                g = bench_srgb_to_linear(g.clamp(0.0, 1.0));
                b = bench_srgb_to_linear(b.clamp(0.0, 1.0));
            }
            let max_c = r.max(g).max(b);
            let (final_r, final_g, final_b) = if max_c > 1.0 {
                let min_c = r.min(g).min(b);
                let compression_factor =
                    (1.0 - (max_c - 1.0) / (safe_highlight_compression - 1.0)).clamp(0.0, 1.0);
                let compressed_r = min_c + (r - min_c) * compression_factor;
                let compressed_g = min_c + (g - min_c) * compression_factor;
                let compressed_b = min_c + (b - min_c) * compression_factor;
                let compressed_max = compressed_r.max(compressed_g).max(compressed_b);
                if compressed_max > 1e-6 {
                    let rescale = max_c / compressed_max;
                    (compressed_r * rescale, compressed_g * rescale, compressed_b * rescale)
                } else {
                    (max_c, max_c, max_c)
                }
            } else {
                (r, g, b)
            };
            p[0] = final_r.clamp(0.0, clamp_limit);
            p[1] = final_g.clamp(0.0, clamp_limit);
            p[2] = final_b.clamp(0.0, clamp_limit);
        });
    }
}

/// Same math with the (never-taken for Bayer) linear/ungamma branch removed from the
/// per-pixel loop. Measurement-only reference for what hoisting that branch would give.
fn post_rescale_highlight_no_linear_branch(
    inter: &mut Intermediate,
    rescale_factor: f32,
    hc: f32,
    fast: bool,
) {
    let safe_hc = hc.max(1.01);
    let clamp_limit = if fast { 1.0 } else { safe_hc };
    if let Intermediate::ThreeColor(pixels) = inter {
        pixels.data.iter_mut().for_each(|p| {
            let r = (p[0] * rescale_factor).max(0.0);
            let g = (p[1] * rescale_factor).max(0.0);
            let b = (p[2] * rescale_factor).max(0.0);
            let max_c = r.max(g).max(b);
            let (fr, fg, fb) = if max_c > 1.0 {
                let min_c = r.min(g).min(b);
                let cf = (1.0 - (max_c - 1.0) / (safe_hc - 1.0)).clamp(0.0, 1.0);
                let cr = min_c + (r - min_c) * cf;
                let cg = min_c + (g - min_c) * cf;
                let cb = min_c + (b - min_c) * cf;
                let cm = cr.max(cg).max(cb);
                if cm > 1e-6 {
                    let s = max_c / cm;
                    (cr * s, cg * s, cb * s)
                } else {
                    (max_c, max_c, max_c)
                }
            } else {
                (r, g, b)
            };
            p[0] = fr.clamp(0.0, clamp_limit);
            p[1] = fg.clamp(0.0, clamp_limit);
            p[2] = fb.clamp(0.0, clamp_limit);
        });
    }
}

/// Step-by-step replica of raw_processing::develop_internal (quality mode, non-linear raw)
/// with timing between steps. Same calls, same order, same allocations.
fn develop_internal_timed(bytes: &[u8], hc: f32) -> Vec<(String, f64)> {
    let mut out = Vec::new();
    let t_all = Instant::now();
    let mut t = Instant::now();
    let mut lap = |name: &str, out: &mut Vec<(String, f64)>| {
        out.push((name.to_string(), ms(t.elapsed())));
        t = Instant::now();
    };
    let source = RawSource::new_from_slice(bytes);
    let decoder = rawler::get_decoder(&source).unwrap();
    let mut raw_image: RawImage = decoder
        .raw_image(&source, &RawDecodeParams::default(), false)
        .unwrap();
    lap("1 decode (get_decoder+raw_image)", &mut out);
    let metadata = decoder
        .raw_metadata(&source, &RawDecodeParams::default())
        .unwrap();
    let orientation = metadata
        .exif
        .orientation
        .map(rawler::decoders::Orientation::from_u16)
        .unwrap_or(rawler::decoders::Orientation::Normal);
    lap("2 raw_metadata", &mut out);
    let white = raw_image.whitelevel.0.first().cloned().unwrap_or(u16::MAX as u32) as f32;
    let black = raw_image.blacklevel.levels.first().map(|r| r.as_f32()).unwrap_or(0.0);
    for level in raw_image.whitelevel.0.iter_mut() {
        *level = u32::MAX;
    }
    let developer = production_developer(false);
    raw_image.wb_coeffs =
        crate::multi_exposure::neutralize_wb_if_multiexposure(raw_image.wb_coeffs, bytes);
    lap("3 setup", &mut out);
    let mut inter = developer.develop_intermediate(&raw_image).unwrap();
    lap("4 develop_intermediate (scale+PPG+WB/matrix+crop)", &mut out);
    drop(raw_image);
    lap("5 drop(raw_image)", &mut out);
    let rescale_factor = (u32::MAX as f32 - black) / (white - black).max(1.0);
    post_rescale_highlight(&mut inter, rescale_factor, hc, false);
    lap("6 rescale+highlight loop (serial)", &mut out);
    let img = intermediate_to_rgba32f(&inter);
    lap("7 to Rgba32F from_fn (serial)", &mut out);
    drop(inter);
    lap("8 drop(intermediate)", &mut out);
    let img = img.map(|i| crate::image_processing::apply_orientation(i, orientation));
    lap(&format!("8b apply_orientation ({:?})", orientation), &mut out);
    drop(img);
    lap("9 drop(output image)", &mut out);
    out.push(("TOTAL (excl. output drop)".to_string(), ms(t_all.elapsed()) - out.last().map(|x| x.1).unwrap_or(0.0)));
    out
}

/// Copy of develop_internal's ImageBuffer::from_fn conversion to Rgba32F (serial).
fn intermediate_to_rgba32f(inter: &Intermediate) -> Option<DynamicImage> {
    if let Intermediate::ThreeColor(pixels) = inter {
        let dim = inter.dim();
        let (width, height) = (dim.w as u32, dim.h as u32);
        let buffer = ImageBuffer::<Rgba<f32>, _>::from_fn(width, height, |x, y| {
            let p = pixels.data[(y * width + x) as usize];
            Rgba([p[0], p[1], p[2], 1.0])
        });
        Some(DynamicImage::ImageRgba32F(buffer))
    } else {
        None
    }
}

/// Uncached read (F_NOCACHE) to estimate cold external-SSD throughput.
fn read_nocache(path: &Path) -> std::io::Result<Vec<u8>> {
    use std::os::fd::AsRawFd;
    let mut f = fs::File::open(path)?;
    unsafe {
        libc::fcntl(f.as_raw_fd(), libc::F_NOCACHE, 1);
    }
    let mut buf = Vec::with_capacity(f.metadata()?.len() as usize);
    f.read_to_end(&mut buf)?;
    Ok(buf)
}

/// Replica of the read_exif_for_paths command body (minus tauri spawn_blocking).
fn read_exif_for_paths_core(paths: &[String]) -> HashMap<String, HashMap<String, String>> {
    paths
        .par_iter()
        .filter_map(|virtual_path| {
            let (source_path, _) = parse_virtual_path(virtual_path);
            let source_path_str = source_path.to_string_lossy().to_string();
            let map = if let Some(sidecar_exif) =
                crate::exif_processing::read_rrexif_sidecar(&source_path)
            {
                sidecar_exif
            } else if crate::file_management::is_cloud_placeholder(&source_path) {
                HashMap::new()
            } else if let Ok(mmap) = read_file_mapped(&source_path) {
                crate::exif_processing::read_exif_data(&source_path_str, &mmap)
            } else if let Ok(bytes) = fs::read(&source_path) {
                crate::exif_processing::read_exif_data(&source_path_str, &bytes)
            } else {
                HashMap::new()
            };
            if map.is_empty() {
                None
            } else {
                Some((virtual_path.clone(), map))
            }
        })
        .collect()
}

/// Replica of generate_single_thumbnail_and_cache for an *unedited* RAW
/// (sidecar parse -> cache hash -> embedded preview -> encode -> write).
fn thumbnail_unedited_raw(
    path: &Path,
    settings: &AppSettings,
    cache_dir: &Path,
) -> Option<(u32, u32, usize)> {
    let path_str = path.to_string_lossy().to_string();
    let (source_path, sidecar_path) = parse_virtual_path(&path_str);
    let adjustments_bytes = if let Ok(content) = fs::read_to_string(&sidecar_path)
        && let Ok(meta) = serde_json::from_str::<ImageMetadata>(&content)
    {
        let is_raw = crate::formats::is_raw_file(&path_str);
        let tm = resolve_tonemapper_override(settings, is_raw);
        let _ = is_image_edited(&meta.adjustments, is_raw, tm);
        serde_json::to_vec(&meta.adjustments).unwrap_or_default()
    } else {
        Vec::new()
    };
    let hash = bench_hooks::compute_thumbnail_cache_hash(&path_str, &adjustments_bytes)?;
    let target = settings.thumbnail_resolution.unwrap_or(720);
    // generate_thumbnail_data re-reads the sidecar; unedited RAW -> embedded preview.
    let _ = fs::read_to_string(&sidecar_path);
    let preview = bench_hooks::try_load_embedded_raw_preview(&source_path, target)?;
    let (w, h) = preview.dimensions();
    let data = bench_hooks::encode_thumbnail(&preview, target).ok()?;
    let _ = fs::write(cache_dir.join(format!("{}.jpg", hash)), &data);
    Some((w, h, data.len()))
}

