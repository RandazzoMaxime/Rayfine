/// Readback path: processor.run(skip_readback=false, display=false) -> RGBA8 image.
fn render_readback(
    p: &GpuProcessor,
    view: &wgpu::TextureView,
    w: u32,
    h: u32,
    adj: &serde_json::Value,
    tm: Option<u32>,
    roi: Option<Roi>,
) -> DynamicImage {
    let (px, ow, oh, _, _) = p
        .run(
            view,
            w,
            h,
            RenderRequest {
                adjustments: get_all_adjustments_from_json(adj, true, tm),
                mask_bitmaps: &[],
                lut: None,
                roi,
            },
            false,
            false,
        )
        .expect("gpu run failed");
    DynamicImage::ImageRgba8(ImageBuffer::<Rgba<u8>, _>::from_raw(ow, oh, px).unwrap())
}

/// Display path (use_wgpu_renderer = true): run(skip_readback, output_to_display),
/// copy working->output like process_and_get_dynamic_image_inner, then wait for the GPU
/// (the app polls with a 500ms timeout right after, before emitting wgpu-frame-ready).
/// Surface present is not included (no window).
fn render_display(
    ctx: &GpuContext,
    p: &GpuProcessor,
    view: &wgpu::TextureView,
    w: u32,
    h: u32,
    adj: &serde_json::Value,
    tm: Option<u32>,
    roi: Option<Roi>,
) {
    let (_, out_w, out_h, out_x, out_y) = p
        .run(
            view,
            w,
            h,
            RenderRequest {
                adjustments: get_all_adjustments_from_json(adj, true, tm),
                mask_bitmaps: &[],
                lut: None,
                roi,
            },
            true,
            true,
        )
        .expect("gpu run failed");
    let mut enc = ctx
        .device
        .create_command_encoder(&wgpu::CommandEncoderDescriptor { label: None });
    let origin = wgpu::Origin3d {
        x: out_x,
        y: out_y,
        z: 0,
    };
    enc.copy_texture_to_texture(
        wgpu::TexelCopyTextureInfo {
            texture: &p.working_texture,
            mip_level: 0,
            origin,
            aspect: wgpu::TextureAspect::All,
        },
        wgpu::TexelCopyTextureInfo {
            texture: &p.output_texture,
            mip_level: 0,
            origin,
            aspect: wgpu::TextureAspect::All,
        },
        wgpu::Extent3d {
            width: out_w,
            height: out_h,
            depth_or_array_layers: 1,
        },
    );
    ctx.queue.submit(Some(enc.finish()));
    gpu_wait(ctx);
}

/// Standalone replica of GpuProcessor's separable blur passes (same blur.wgsl, same
/// bind layout, same dispatch sizes, one submit per blur) to isolate their GPU cost.
#[repr(C)]
#[derive(Debug, Copy, Clone, bytemuck::Pod, bytemuck::Zeroable)]
struct BenchBlurParams {
    radius: u32,
    tile_offset_x: u32,
    tile_offset_y: u32,
    input_width: u32,
    input_height: u32,
    _pad1: u32,
    _pad2: u32,
    _pad3: u32,
}

struct BlurBench {
    bgl: wgpu::BindGroupLayout,
    h: wgpu::ComputePipeline,
    v: wgpu::ComputePipeline,
    params: wgpu::Buffer,
    ping_view: wgpu::TextureView,
    out_view: wgpu::TextureView,
}

impl BlurBench {
    fn new(ctx: &GpuContext, tile_w: u32, tile_h: u32) -> Self {
        let device = &ctx.device;
        let module = device.create_shader_module(wgpu::ShaderModuleDescriptor {
            label: Some("bench blur"),
            source: wgpu::ShaderSource::Wgsl(include_str!("shaders/blur.wgsl").into()),
        });
        let bgl = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: None,
            entries: &[
                wgpu::BindGroupLayoutEntry {
                    binding: 0,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Texture {
                        sample_type: wgpu::TextureSampleType::Float { filterable: false },
                        view_dimension: wgpu::TextureViewDimension::D2,
                        multisampled: false,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 1,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::StorageTexture {
                        access: wgpu::StorageTextureAccess::WriteOnly,
                        format: wgpu::TextureFormat::Rgba16Float,
                        view_dimension: wgpu::TextureViewDimension::D2,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 2,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Uniform,
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
            ],
        });
        let layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: None,
            bind_group_layouts: &[Some(&bgl)],
            immediate_size: 0,
        });
        let mk = |entry: &str| {
            device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {
                label: None,
                layout: Some(&layout),
                module: &module,
                entry_point: Some(entry),
                compilation_options: Default::default(),
                cache: None,
            })
        };
        let h = mk("horizontal_blur");
        let v = mk("vertical_blur");
        let params = device.create_buffer(&wgpu::BufferDescriptor {
            label: None,
            size: std::mem::size_of::<BenchBlurParams>() as u64,
            usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        let desc = wgpu::TextureDescriptor {
            label: None,
            size: wgpu::Extent3d {
                width: tile_w,
                height: tile_h,
                depth_or_array_layers: 1,
            },
            mip_level_count: 1,
            sample_count: 1,
            dimension: wgpu::TextureDimension::D2,
            format: wgpu::TextureFormat::Rgba16Float,
            usage: wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::STORAGE_BINDING,
            view_formats: &[],
        };
        let ping_view = device.create_texture(&desc).create_view(&Default::default());
        let out_view = device.create_texture(&desc).create_view(&Default::default());
        Self {
            bgl,
            h,
            v,
            params,
            ping_view,
            out_view,
        }
    }

    /// One run_blur() call as in GpuProcessor::run (tile at offset x0,y0 of size iw x ih).
    fn run(
        &self,
        ctx: &GpuContext,
        input: &wgpu::TextureView,
        radius: u32,
        x0: u32,
        y0: u32,
        iw: u32,
        ih: u32,
    ) {
        let device = &ctx.device;
        ctx.queue.write_buffer(
            &self.params,
            0,
            bytemuck::bytes_of(&BenchBlurParams {
                radius,
                tile_offset_x: x0,
                tile_offset_y: y0,
                input_width: iw,
                input_height: ih,
                _pad1: 0,
                _pad2: 0,
                _pad3: 0,
            }),
        );
        let mut enc = device.create_command_encoder(&Default::default());
        let bg = |src: &wgpu::TextureView, dst: &wgpu::TextureView| {
            device.create_bind_group(&wgpu::BindGroupDescriptor {
                label: None,
                layout: &self.bgl,
                entries: &[
                    wgpu::BindGroupEntry {
                        binding: 0,
                        resource: wgpu::BindingResource::TextureView(src),
                    },
                    wgpu::BindGroupEntry {
                        binding: 1,
                        resource: wgpu::BindingResource::TextureView(dst),
                    },
                    wgpu::BindGroupEntry {
                        binding: 2,
                        resource: self.params.as_entire_binding(),
                    },
                ],
            })
        };
        let hbg = bg(input, &self.ping_view);
        {
            let mut c = enc.begin_compute_pass(&Default::default());
            c.set_pipeline(&self.h);
            c.set_bind_group(0, &hbg, &[]);
            c.dispatch_workgroups(iw.div_ceil(256), ih, 1);
        }
        let vbg = bg(&self.ping_view, &self.out_view);
        {
            let mut c = enc.begin_compute_pass(&Default::default());
            c.set_pipeline(&self.v);
            c.set_bind_group(0, &vbg, &[]);
            c.dispatch_workgroups(iw, ih.div_ceil(256), 1);
        }
        ctx.queue.submit(Some(enc.finish()));
    }
}

/// Times the 4 blurs GpuProcessor::run always executes for one tile.
/// scale = min(image_w, image_h)/1080 as in run(); radii = ceil(base*scale).
fn bench_blurs(
    rep: &mut Report,
    ctx: &GpuContext,
    bb: &BlurBench,
    input: &wgpu::TextureView,
    img_w: u32,
    img_h: u32,
    tile: (u32, u32, u32, u32),
    label: &str,
    reps: usize,
) {
    let scale = (img_w.min(img_h) as f32) / 1080.0;
    let (x0, y0, iw, ih) = tile;
    let mut total = Vec::new();
    for (name, base) in [
        ("sharpness r=1", 1.0f32),
        ("tonal r=3.5", 3.5),
        ("clarity r=8", 8.0),
        ("structure r=40", 40.0),
    ] {
        let radius = (base * scale).ceil().max(1.0) as u32;
        let (s, _) = bench(reps, || {
            bb.run(ctx, input, radius, x0, y0, iw, ih);
            gpu_wait(ctx);
        });
        rep.acc(
            &format!("  - {} blur {} (radius {}px, {} taps x2 passes)", label, name, radius, 2 * radius + 1),
            s,
            "h+v separable, gaussian exp() per tap",
        );
    }
    let (s, _) = bench(reps, || {
        for base in [1.0f32, 3.5, 8.0, 40.0] {
            let radius = (base * scale).ceil().max(1.0) as u32;
            bb.run(ctx, input, radius, x0, y0, iw, ih);
        }
        gpu_wait(ctx);
    });
    total.extend(s);
    rep.acc(
        &format!("  - {} all 4 blurs (one tile {}x{})", label, iw, ih),
        total,
        "always executed, independent of slider values",
    );
}

